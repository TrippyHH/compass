import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import {
  databaseRoot,
  revision,
  revisions,
  loadRevision,
  sourceRecordSql,
  hash,
  cli,
  databaseMarker,
  literal,
  lockKey,
} from "./db-common.mjs";

function guardSql(from) {
  return `DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_database WHERE datname=current_database() AND shobj_description(oid,'pg_database')=${literal(databaseMarker)}) THEN RAISE EXCEPTION 'Unregistered database'; END IF;
 IF (SELECT count(*) FROM web_meta.pgmigrations) <> ${revisions.indexOf(from.id) + 1} OR NOT EXISTS (SELECT 1 FROM web_meta.pgmigrations WHERE name=${literal(from.id)}) OR (SELECT count(*) FROM web_meta.migration_source) <> ${revisions.indexOf(from.id) + 1} OR NOT EXISTS (SELECT 1 FROM web_meta.migration_source WHERE revision=${literal(from.id)} AND sha256=${literal(from.sha256)}) THEN RAISE EXCEPTION 'Unexpected starting revision or source checksum'; END IF;
END $$;`;
}

const migrationEntry = (item) =>
  `${item.up}\n${sourceRecordSql(item)}\nINSERT INTO web_meta.pgmigrations(name,run_on) VALUES (${literal(item.id)},NOW());`;

function upgradeSql(from, to) {
  return `-- Generated by pnpm db:sql -F web; do not edit.
-- ${from.id} -> ${to.id}
BEGIN;
SET LOCAL ROLE compass_web_owner;
SELECT pg_advisory_xact_lock(${lockKey}::bigint);
${guardSql(from)}
${migrationEntry(to)}
COMMIT;
`;
}

export async function generateSql() {
  const sources = await Promise.all(revisions.map((id) => loadRevision(id)));
  const first = sources[0];
  const last = sources.at(-1);
  const migrationSql = sources.map(migrationEntry).join("\n");
  const sql = `-- Generated by pnpm db:sql -F web; do not edit.
-- Owner web/main; Feature 993; PostgreSQL 17; node-pg-migrate 9.0.0.
-- empty -> ${revision}; transaction; recovery via verified backup/new database.
BEGIN;
SET LOCAL ROLE compass_web_owner;
SELECT pg_advisory_xact_lock(${lockKey}::bigint);
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_database WHERE datname=current_database() AND shobj_description(oid,'pg_database')=${literal(databaseMarker)}) THEN RAISE EXCEPTION 'Unregistered database'; END IF;
  IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname NOT IN ('pg_catalog','information_schema') AND n.nspname NOT LIKE 'pg_%') OR EXISTS (SELECT 1 FROM pg_namespace WHERE nspname NOT IN ('public','information_schema') AND nspname NOT LIKE 'pg_%') OR EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public') THEN RAISE EXCEPTION 'Bootstrap requires an empty database'; END IF;
END $$;
CREATE SCHEMA web_meta AUTHORIZATION compass_web_owner;
CREATE TABLE web_meta.pgmigrations (id SERIAL PRIMARY KEY, name varchar(255) NOT NULL, run_on timestamp NOT NULL);
${migrationSql}
COMMIT;
`;
  const artifacts = new Map([["bootstrap.sql", sql]]);
  artifacts.set(
    `upgrades/empty__${first.id}.sql`,
    sql
      .replace(migrationSql, migrationEntry(first))
      .replace(`empty -> ${revision}`, `empty -> ${first.id}`),
  );
  for (let index = 0; index < sources.length - 1; index++) {
    const from = sources[index];
    const to = sources[index + 1];
    artifacts.set(`upgrades/${from.id}__${to.id}.sql`, upgradeSql(from, to));
  }
  const incremental = `upgrades/${sources.at(-2).id}__${last.id}.sql`;
  const manifest = {
    owner: "web",
    databaseKey: "main",
    feature: "993",
    from: "empty",
    to: revision,
    engine: "PostgreSQL 17",
    tool: "node-pg-migrate 9.0.0",
    sourceRevision: "working-tree; fixed by source SHA-256",
    sources: sources.map((item) => ({ source: `migrations/${item.id}.sql`, sha256: item.sha256 })),
    bootstrap: "sql/bootstrap.sql",
    bootstrapSha256: hash(sql),
    incremental: `sql/${incremental}`,
    incrementalSha256: hash(artifacts.get(incremental)),
    generate: "pnpm db:sql -F web",
    apply: `pnpm db:apply-sql -F web -- --from empty --to ${revision}`,
    prerequisites:
      "Provisioned owned empty web/main database, owner/migrator/runtime roles; managed target checks and lock",
    transaction: "single transaction",
    dataImpact:
      "Creates the Web schema, readable slugs and the models.invoke permission; no users or business rows",
    recovery:
      "Restore verified backup into a new owned database; verify permissions/revision; revoke sessions before switching",
  };
  artifacts.set("manifest.json", JSON.stringify(manifest, null, 2) + "\n");
  return artifacts;
}

export async function writeSql(check = false) {
  const artifacts = await generateSql();
  if (!check) await mkdir(new URL("sql/upgrades/", databaseRoot), { recursive: true });
  for (const [name, content] of artifacts) {
    const target = new URL(`sql/${name}`, databaseRoot);
    if (check) {
      if ((await readFile(target, "utf8")) !== content) throw new Error(`SQL drift: ${name}`);
    } else await writeFile(target, content);
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url))
  cli(async () => {
    if (process.argv.slice(2).some((a) => a !== "--check"))
      throw new Error("Only --check is supported");
    await writeSql(process.argv.includes("--check"));
    console.log(
      process.argv.includes("--check")
        ? "Web SQL matches its source."
        : "Web SQL artifacts generated.",
    );
  });
