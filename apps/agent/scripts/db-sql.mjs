import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "..");
const dbRoot = path.join(appRoot, "db", "main");
const revisions = [
  { id: "0001", name: "0001_demo_fixture" },
  { id: "0002", name: "0002_model_runtime" },
];
const head = revisions.at(-1);
const engine = "PostgreSQL 17";
const tool = "Alembic 1.15 / SQLAlchemy 2.0";

const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");

function sourceDigests() {
  return revisions.map(({ name }) => {
    const file = path.join(appRoot, "migrations", "versions", `${name}.py`);
    return { source: `migrations/versions/${name}.py`, sha256: hash(readFileSync(file)) };
  });
}

function runAlembic(range) {
  const args = ["-m", "alembic", "-c", "alembic.ini", "upgrade", range, "--sql"];
  const python = process.env.COMPASS_AGENT_PYTHON;
  const stdout = python
    ? execFileSync(python, args, { cwd: appRoot, encoding: "utf8" })
    : execFileSync(
        "uv",
        ["run", "--locked", "--package", "compass-agent", "python", ...args],
        { cwd: appRoot, encoding: "utf8" },
      );
  return stdout.replace(/\r\n/g, "\n").trimEnd() + "\n";
}

function header({ from, to, sources }) {
  return [
    "-- Generated by pnpm db:sql -F agent; do not edit.",
    `-- Owner agent/main; Feature 993; ${engine}; ${tool}.`,
    `-- ${from} -> ${to}; single migration transaction; recovery via verified backup/new database.`,
    ...sources.map((item) => `-- source: ${item.source} (sha256 ${item.sha256})`),
    "",
  ].join("\n");
}

export function buildArtifacts({ bootstrapBody, firstBody, upgradeBody }) {
  const sources = sourceDigests();
  const artifacts = new Map([
    [
      "bootstrap.sql",
      header({ from: "empty", to: head.name, sources }) + bootstrapBody,
    ],
    [
      `upgrades/empty__${revisions[0].name}.sql`,
      header({ from: "empty", to: revisions[0].name, sources }) + firstBody,
    ],
    [
      `upgrades/${revisions[0].name}__${head.name}.sql`,
      header({ from: revisions[0].name, to: head.name, sources }) + upgradeBody,
    ],
  ]);
  const bootstrap = artifacts.get("bootstrap.sql");
  const incremental = artifacts.get(`upgrades/${revisions[0].name}__${head.name}.sql`);
  const manifest = {
    owner: "agent",
    databaseKey: "main",
    feature: "993",
    from: "empty",
    to: head.name,
    engine,
    tool,
    sourceRevision: "working-tree; fixed by source SHA-256",
    sources,
    bootstrap: "sql/bootstrap.sql",
    bootstrapSha256: hash(bootstrap),
    incremental: `sql/upgrades/${revisions[0].name}__${head.name}.sql`,
    incrementalSha256: hash(incremental),
    generate: "pnpm db:sql -F agent",
    apply: "pnpm db:migrate -F agent",
    prerequisites:
      "Owned agent/main database; DATABASE_URL only for offline SQL generation; apply with the Alembic migration entry",
    transaction: "single transaction (PostgreSQL DDL)",
    dataImpact:
      "Adds model_provider, model_change and model_call; existing demo and business data are unchanged",
    recovery:
      "Restore a verified backup into a new owned database; verify alembic_version=0002 and runtime grants before switching",
  };
  artifacts.set("manifest.json", JSON.stringify(manifest, null, 2) + "\n");
  return { artifacts, manifest };
}

export function generateArtifacts() {
  return buildArtifacts({
    bootstrapBody: runAlembic("head"),
    firstBody: runAlembic(revisions[0].id),
    upgradeBody: runAlembic(`${revisions[0].id}:${revisions[1].id}`),
  });
}

export function writeArtifacts(check = false) {
  const { artifacts } = generateArtifacts();
  if (!check) mkdirSync(path.join(dbRoot, "sql", "upgrades"), { recursive: true });
  for (const [name, content] of artifacts) {
    const target = path.join(dbRoot, "sql", name);
    if (check) {
      const actual = readFileSync(target, "utf8");
      if (actual !== content) throw new Error(`SQL drift: ${name}; run pnpm db:sql -F agent`);
    } else {
      writeFileSync(target, content);
    }
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  try {
    writeArtifacts(check);
    console.log(
      check
        ? "Agent SQL matches its migration source."
        : "Agent SQL artifacts generated.",
    );
  } catch (error) {
    console.error(String(error.message).replace(/postgres(?:ql)?:\/\/\S+/g, "[redacted]"));
    process.exitCode = 1;
  }
}

